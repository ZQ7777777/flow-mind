export function assertDeck() {
  if (slides.length !== 9) throw new Error(`Expected 9 slides, got ${slides.length}`);
  const ids = new Set(slides.map((slide) => slide.id));
  if (ids.size !== slides.length) throw new Error("Slide IDs must be unique");
  const minutes = Number(slides.reduce((sum, slide) => sum + slide.minutes, 0).toFixed(2));
  if (minutes !== deck.plannedMinutes) throw new Error(`Expected ${deck.plannedMinutes} minutes, got ${minutes}`);
}
